#!/usr/bin/env python3
"""Download the Bank of Israel representative USD/ILS rate (RER_USD_ILS)
and write it to data/usd_ils_rates.js and data/usd_ils_rates.json.

The Bank of Israel API rejects cross-origin browser requests, so the web app
cannot call it directly. Instead the rates are bundled in the repo and refreshed
by a scheduled GitHub Action (.github/workflows/update-rates.yml).

Usage: python3 scripts/update_rates.py [--start 2019-12-01]
"""
import argparse
import csv
import datetime as dt
import io
import json
import pathlib
import urllib.request

API = (
    "https://edge.boi.gov.il/FusionEdgeServer/sdmx/v2/data/dataflow/"
    "BOI.STATISTICS/EXR/1.0/RER_USD_ILS?startPeriod={start}&endPeriod={end}&format=csv"
)
ROOT = pathlib.Path(__file__).resolve().parent.parent


def fetch(start: str, end: str) -> dict:
    req = urllib.request.Request(API.format(start=start, end=end),
                                 headers={"User-Agent": "espp-rsu-report-generator"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        text = resp.read().decode("utf-8")
    rates = {}
    for row in csv.DictReader(io.StringIO(text)):
        if row.get("SERIES_CODE") != "RER_USD_ILS" or not row.get("OBS_VALUE"):
            continue
        rates[row["TIME_PERIOD"]] = float(row["OBS_VALUE"])
    if len(rates) < 10:
        raise SystemExit(f"Suspiciously few rates returned ({len(rates)}); aborting")
    return dict(sorted(rates.items()))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--start", default="2019-12-01")
    args = ap.parse_args()
    end = dt.date.today().isoformat()
    rates = fetch(args.start, end)
    payload = {
        "source": "Bank of Israel - representative rate (שער יציג), series RER_USD_ILS",
        "series": "RER_USD_ILS",
        "first": next(iter(rates)),
        "last": next(reversed(rates)),
        "count": len(rates),
        "rates": rates,
    }
    out_dir = ROOT / "data"
    out_dir.mkdir(exist_ok=True)
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    (out_dir / "usd_ils_rates.json").write_text(body + "\n", encoding="utf-8")
    # A .js twin so index.html also works when opened from file:// (no fetch).
    (out_dir / "usd_ils_rates.js").write_text(
        "// Generated by scripts/update_rates.py - do not edit by hand.\n"
        f"window.USD_ILS_RATES = {body};\n", encoding="utf-8")
    print(f"Wrote {len(rates)} rates {payload['first']} .. {payload['last']}")


if __name__ == "__main__":
    main()
